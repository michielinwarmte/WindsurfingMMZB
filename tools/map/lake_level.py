"""Finds the lake level of Silvaplanersee and writes the map's position settings.

Documentation/MAP_SILVAPLANA_PLAN.md, M0 and MD1. In swissALTI3D a lake is a flat surface at
its water level, so the most common height over the lake is the lake level. The result goes to
Game/maps/silvaplana/map_config.tres (generated: change this script, not that file) and
.map_data/work/lake.json.

Run from the repo root: python tools/map/lake_level.py
"""
import json

import numpy as np

import readers
import silvaplana_area as area

# The game's origin (plan MD1): the middle of the lake, rounded to 100 m.
ORIGIN_EAST_M = 2_780_500.0
ORIGIN_NORTH_M = 1_146_600.0

CONFIG_TEMPLATE = """\
[gd_resource type="Resource" script_class="MapConfig" load_steps=2 format=3]

[ext_resource type="Script" path="res://maps/map_config.gd" id="1"]

; Generated by tools/map/lake_level.py from swissALTI3D. Change the script, not this file.

[resource]
script = ExtResource("1")
map_name = "Lake Silvaplana"
origin_east_m = {origin_east}
origin_north_m = {origin_north}
lake_level_m = {lake_level}
"""


def lake_level() -> tuple[float, int]:
    """The most common height (to the centimetre) of swissALTI3D inside the lake's box."""
    counts: dict[float, int] = {}
    for east_km, north_km in area.shore_tiles():
        tile = readers.read_alti3d_tile(east_km, north_km)
        rows = np.arange(tile.heights.shape[0])
        columns = np.arange(tile.heights.shape[1])
        north = tile.north_m - (rows + 0.5) * tile.cell_m
        east = tile.west_m + (columns + 0.5) * tile.cell_m
        in_rows = (north >= area.LAKE_NORTH_M[0]) & (north <= area.LAKE_NORTH_M[1])
        in_columns = (east >= area.LAKE_EAST_M[0]) & (east <= area.LAKE_EAST_M[1])
        heights = tile.heights[np.ix_(in_rows, in_columns)]
        heights = heights[~np.isnan(heights)]
        values, numbers = np.unique(np.round(heights, 2), return_counts=True)
        for value, number in zip(values, numbers):
            counts[float(value)] = counts.get(float(value), 0) + int(number)
    level = max(counts, key=counts.get)
    return round(level, 2), counts[level]


def main() -> None:
    level, cells = lake_level()
    print(f"Lake level: {level:.2f} m above sea level ({cells:,} cells of 0.5 m, {cells * 0.25 / 1e6:.2f} km2 flat at that height)")

    area.WORK_DIR.mkdir(parents=True, exist_ok=True)
    (area.WORK_DIR / "lake.json").write_text(json.dumps({
        "lake_level_m": level,
        "flat_cells_0_5m": cells,
        "origin_east_m": ORIGIN_EAST_M,
        "origin_north_m": ORIGIN_NORTH_M,
    }, indent=1))

    config = area.GAME_MAP_DIR / "map_config.tres"
    config.parent.mkdir(parents=True, exist_ok=True)
    config.write_text(CONFIG_TEMPLATE.format(origin_east=ORIGIN_EAST_M, origin_north=ORIGIN_NORTH_M, lake_level=level), newline="\n")
    print(f"Wrote {config.relative_to(area.REPO_ROOT)}")


if __name__ == "__main__":
    main()
